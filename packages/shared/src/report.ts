import { toOperation, type CrudOp, type Operation } from './crud.js';
import { assessRisk, riskAtLeast, type Risk } from './risk.js';
import type { Interaction, Prompt, ToolCall } from './types.js';

export type ReportKind = 'pir' | 'rca' | 'changelog' | 'rfc';

export const REPORT_KINDS: { id: ReportKind; label: string; blurb: string }[] = [
  { id: 'pir', label: 'Post-incident review', blurb: 'Summary, timeline, actions taken and follow-ups.' },
  { id: 'rca', label: 'Root cause analysis', blurb: 'Evidence from failures and repeated errors, with causal analysis prompts.' },
  { id: 'changelog', label: 'Change log', blurb: 'Every file and command change, grouped by path.' },
  { id: 'rfc', label: 'RFC / change proposal', blurb: 'Motivation, what was changed, risks and rollback.' },
];

export interface GuardEvent {
  ts: number;
  tool: string | null;
  target: string | null;
  decision: string;
  reason: string;
}

export interface ReportInput {
  kind: ReportKind;
  session: {
    id: string;
    title: string | null;
    project: string;
    cwd: string | null;
    gitBranch: string | null;
    models: string[];
    startMs: number | null;
    endMs: number | null;
    nInteractions: number;
    nErrors: number;
    outTokens: number;
  };
  prompts: Prompt[];
  items: Interaction[];
  guard?: GuardEvent[];
  generatedMs: number;
}

interface Rec {
  ts: number | null;
  index: number;
  tool: ToolCall;
  op: Operation | null;
  risk: Risk;
  reasons: string[];
}

const iso = (ms: number | null | undefined): string => (ms ? new Date(ms).toISOString().replace('T', ' ').slice(0, 19) : '—');

function duration(a: number | null, b: number | null): string {
  if (!a || !b || b < a) return 'unknown';
  const s = Math.round((b - a) / 1000);
  if (s < 60) return `${s}s`;
  if (s < 3600) return `${Math.floor(s / 60)}m ${s % 60}s`;
  return `${Math.floor(s / 3600)}h ${Math.floor((s % 3600) / 60)}m`;
}

const cell = (s: string, max = 140): string => {
  const one = s.replace(/\s+/g, ' ').trim();
  return (one.length > max ? `${one.slice(0, max)}…` : one).replaceAll('|', '\\|');
};

/** A fenced block whose fence is longer than any backtick run inside, so content cannot break out. */
function fence(code: string, lang = ''): string {
  const longest = Math.max(0, ...(code.match(/`+/g) ?? []).map((m) => m.length));
  const f = '`'.repeat(Math.max(3, longest + 1));
  return `${f}${lang}\n${code.replace(/\s+$/, '')}\n${f}`;
}

const todo = (what: string): string => `> **TODO (human):** ${what}`;
const table = (head: string[], rows: string[][]): string =>
  rows.length ? [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n') : '_None recorded._';

function records(items: Interaction[]): Rec[] {
  const out: Rec[] = [];
  for (const it of items) {
    for (const tool of it.tools) {
      const r = assessRisk(tool);
      out.push({ ts: it.startMs, index: it.index, tool, op: toOperation(tool), risk: r.level, reasons: r.reasons });
    }
  }
  return out;
}

const firstLine = (s: string): string => s.trim().split('\n')[0] ?? '';
const changes = (recs: Rec[]): Rec[] => recs.filter((r) => r.op && (['create', 'update', 'delete'] as CrudOp[]).includes(r.op.op));

function header(i: ReportInput, title: string): string[] {
  const s = i.session;
  return [
    `# ${title}: ${s.title ?? s.id}`,
    '',
    `> Draft generated by Agent ATO on ${iso(i.generatedMs)} UTC from Claude Code logs. Facts below come from the recorded session;`,
    '> sections marked **TODO (human)** need a person, because the logs cannot show impact, intent or root cause on their own.',
    '',
    table(['Field', 'Value'], [
      ['Session', `\`${s.id}\``],
      ['Project', cell(s.project)],
      ['Working directory', s.cwd ? `\`${cell(s.cwd)}\`` : '—'],
      ['Git branch', s.gitBranch ? `\`${s.gitBranch}\`` : '—'],
      ['Models', s.models.join(', ') || '—'],
      ['Started (UTC)', iso(s.startMs)],
      ['Ended (UTC)', iso(s.endMs)],
      ['Duration', duration(s.startMs, s.endMs)],
      ['Interactions / tool calls', `${s.nInteractions} / ${i.items.reduce((n, it) => n + it.tools.length, 0)}`],
      ['Failed tool calls', String(s.nErrors)],
    ]),
    '',
  ];
}

function summary(i: ReportInput, recs: Rec[]): string {
  const ch = changes(recs);
  const n = (op: CrudOp): number => ch.filter((r) => r.op!.op === op).length;
  const risky = recs.filter((r) => riskAtLeast(r.risk, 'high')).length;
  const ask = i.prompts[0]?.text.trim().replace(/\s+/g, ' ');
  return [
    ask ? `The session began with this request: "${ask.length > 400 ? `${ask.slice(0, 400)}…` : ask}"` : 'No user prompt was recorded.',
    '',
    `Over ${duration(i.session.startMs, i.session.endMs)} the agent made ${i.session.nInteractions} model calls and ${recs.length} tool calls. ` +
      `It created ${n('create')}, updated ${n('update')} and deleted ${n('delete')} item(s) through file tools and shell commands. ` +
      `${i.session.nErrors} interaction(s) contained a failed tool call and ${risky} action(s) were rated high or critical risk.`,
  ].join('\n');
}

function timeline(i: ReportInput, recs: Rec[]): string {
  type Ev = { ts: number; text: string };
  const ev: Ev[] = [];
  for (const p of i.prompts) if (p.ts) ev.push({ ts: p.ts, text: `**User request:** ${cell(p.text, 200)}` });
  for (const r of recs) {
    if (!r.ts) continue;
    if (r.tool.status === 'error') ev.push({ ts: r.ts, text: `**Tool error** (${r.tool.name}): \`${cell(r.tool.label, 80)}\`: ${cell(firstLine(r.tool.output), 120)}` });
    if (riskAtLeast(r.risk, 'high')) ev.push({ ts: r.ts, text: `**${r.risk}-risk action** (${r.tool.name}): \`${cell(r.op?.target || r.tool.label, 100)}\`: ${r.reasons.join('; ')}` });
  }
  for (const g of i.guard ?? []) ev.push({ ts: g.ts, text: `**Guard ${g.decision}** (${g.tool ?? 'tool'}): \`${cell(g.target ?? '', 100)}\`: ${cell(g.reason, 120)}` });
  ev.sort((a, b) => a.ts - b.ts);
  const shown = ev.slice(0, 150);
  return [
    table(['Time (UTC)', 'Event'], shown.map((e) => [iso(e.ts), e.text])),
    ev.length > shown.length ? `\n_${ev.length - shown.length} further events omitted; see the Agent ATO audit log._` : '',
  ].join('\n');
}

function changeTable(recs: Rec[]): string {
  const ch = changes(recs);
  const byPath = new Map<string, Rec[]>();
  for (const r of ch) {
    const key = r.op!.tool === 'Bash' || r.op!.tool === 'PowerShell' ? `(shell) ${cell(r.op!.target, 80)}` : r.op!.target;
    byPath.set(key, [...(byPath.get(key) ?? []), r]);
  }
  return table(
    ['Target', 'Operations', 'First (UTC)', 'Last (UTC)', 'Highest risk'],
    [...byPath.entries()].map(([target, rs]) => {
      const ops = [...new Set(rs.map((r) => r.op!.op))].join(', ');
      const top = rs.reduce<Risk>((m, r) => (riskAtLeast(r.risk, m) ? r.risk : m), 'low');
      return [`\`${cell(target, 90)}\``, `${ops} ×${rs.length}`, iso(rs[0]!.ts), iso(rs[rs.length - 1]!.ts), top];
    }),
  );
}

function riskTable(recs: Rec[]): string {
  return table(
    ['Time (UTC)', 'Risk', 'Tool', 'Action', 'Why'],
    recs
      .filter((r) => riskAtLeast(r.risk, 'medium'))
      .map((r) => [iso(r.ts), r.risk, r.tool.name, `\`${cell(r.op?.target || r.tool.label, 90)}\``, cell(r.reasons.join('; '), 100)]),
  );
}

function errorSection(recs: Rec[]): string {
  const errs = recs.filter((r) => r.tool.status === 'error');
  if (!errs.length) return '_No failed tool calls were recorded._';
  const groups = new Map<string, Rec[]>();
  for (const r of errs) groups.set(r.tool.label, [...(groups.get(r.tool.label) ?? []), r]);
  const parts: string[] = [];
  for (const [label, rs] of [...groups.entries()].sort((a, b) => b[1].length - a[1].length).slice(0, 12)) {
    parts.push(`### \`${cell(label, 100)}\`: failed ${rs.length}×`, '', `First at ${iso(rs[0]!.ts)} UTC.`, '', fence(rs[0]!.tool.output.slice(0, 1200) || '(no output)'), '');
  }
  return parts.join('\n');
}

function narration(i: ReportInput): string {
  const notes = i.items.filter((it) => it.narration.trim() && (it.hasError || it.tools.some((t) => riskAtLeast(assessRisk(t).level, 'high')))).slice(0, 12);
  if (!notes.length) return '_No agent commentary was recorded around errors or risky actions._';
  return notes
    .map((it) => `- ${iso(it.startMs)} (step ${it.index}${it.hasError ? ', error' : ''}): ${cell(it.narration, 400)}`)
    .join('\n') +
    '\n\n_Claude Code does not store the model\'s private reasoning; this is only the visible commentary the agent wrote between tool calls._';
}

function pir(i: ReportInput, recs: Rec[]): string {
  return [
    ...header(i, 'Post-incident review'),
    '## Status',
    'Draft. Not reviewed.',
    '',
    '## Summary',
    summary(i, recs),
    '',
    '## Impact',
    todo('Who or what was affected, for how long, and how severe. The logs record only what the agent did.'),
    '',
    '## Timeline',
    timeline(i, recs),
    '',
    '## Detection',
    todo('How was the problem noticed (alert, user report, agent error)?'),
    '',
    '## Root cause',
    todo('State the cause. Evidence from this session is under "Failures" below.'),
    '',
    '## Resolution and recovery: changes made by the agent',
    changeTable(recs),
    '',
    '## Agent commentary at key points',
    narration(i),
    '',
    '## What went well',
    todo('Which safeguards or actions helped?'),
    '',
    '## What went poorly',
    todo('Where did tooling, process or the agent fall short?'),
    '',
    '## Action items',
    table(['Action', 'Owner', 'Priority', 'Due'], [['', '', '', '']]),
    '',
    '## Appendix A: failures',
    errorSection(recs),
    '',
    '## Appendix B: risky actions',
    riskTable(recs),
    '',
  ].join('\n');
}

function rca(i: ReportInput, recs: Rec[]): string {
  const errs = recs.filter((r) => r.tool.status === 'error');
  const repeats = [...new Set(errs.map((r) => r.tool.label))].filter((l) => errs.filter((r) => r.tool.label === l).length > 1);
  return [
    ...header(i, 'Root cause analysis'),
    '## Problem statement',
    i.prompts[0]?.text.trim() ? fence(i.prompts[0].text.trim().slice(0, 1500)) : todo('Describe the problem in one or two sentences.'),
    '',
    '## Evidence',
    '### Timeline',
    timeline(i, recs),
    '',
    '### Failures',
    errorSection(recs),
    '',
    '### Repeated failures',
    repeats.length ? repeats.map((l) => `- \`${cell(l, 100)}\` failed ${errs.filter((r) => r.tool.label === l).length}×`).join('\n') : '_No command failed more than once._',
    '',
    '### Agent commentary',
    narration(i),
    '',
    '## Causal analysis',
    todo('Immediate cause: what directly produced the failure?'),
    '',
    todo('Why did that happen? Ask "why" until you reach a cause you can fix (5 whys).'),
    '',
    '## Contributing factors',
    todo('Missing tests, unclear requirements, tooling gaps, permissions, time pressure.'),
    '',
    '## Changes made while investigating',
    changeTable(recs),
    '',
    '## Corrective and preventive actions',
    table(['Action', 'Type (fix / detect / prevent)', 'Owner', 'Due'], [['', '', '', '']]),
    '',
  ].join('\n');
}

function changelog(i: ReportInput, recs: Rec[]): string {
  const ch = changes(recs);
  const group = (op: CrudOp): string[] => {
    const seen = new Map<string, Rec>();
    for (const r of ch.filter((x) => x.op!.op === op)) if (!seen.has(r.op!.target)) seen.set(r.op!.target, r);
    return [...seen.values()].map((r) => `- \`${cell(r.op!.target, 120)}\` (${r.tool.name}, ${iso(r.ts)} UTC${riskAtLeast(r.risk, 'high') ? `, **${r.risk} risk**` : ''})`);
  };
  const section = (name: string, op: CrudOp): string[] => {
    const lines = group(op);
    return [`### ${name}`, ...(lines.length ? lines : ['_None._']), ''];
  };
  const commands = recs.filter((r) => r.op?.op === 'run').slice(0, 40);
  return [
    ...header(i, 'Change log'),
    '## Summary',
    summary(i, recs),
    '',
    '## Changes',
    ...section('Added', 'create'),
    ...section('Changed', 'update'),
    ...section('Removed', 'delete'),
    '## Detail by target',
    changeTable(recs),
    '',
    '## Commands run (not file changes)',
    commands.length ? commands.map((r) => `- ${iso(r.ts)} \`${cell(r.op!.target, 110)}\` → ${r.tool.status}`).join('\n') : '_None._',
    '',
    '## Verification',
    todo('How were these changes tested or reviewed? Link the pull request or ticket.'),
    '',
  ].join('\n');
}

function rfc(i: ReportInput, recs: Rec[]): string {
  const ch = changes(recs);
  const created = [...new Set(ch.filter((r) => r.op!.op === 'create').map((r) => r.op!.target))];
  const deleted = [...new Set(ch.filter((r) => r.op!.op === 'delete').map((r) => r.op!.target))];
  const gitRuns = recs.filter((r) => r.op && /\bgit\s+(commit|push|merge|rebase|reset|checkout)\b/i.test(r.op.code));
  return [
    ...header(i, 'RFC'),
    '## Status',
    'Draft',
    '',
    '## Authors and reviewers',
    todo('Add owners and reviewers.'),
    '',
    '## Motivation',
    i.prompts[0]?.text.trim() ? fence(i.prompts[0].text.trim().slice(0, 1500)) : todo('Why is this change needed?'),
    '',
    '## Proposal: what was changed',
    summary(i, recs),
    '',
    changeTable(recs),
    '',
    '## Design notes from the agent',
    narration(i),
    '',
    '## Alternatives considered',
    todo('What else was considered and why was it rejected? The logs do not record this.'),
    '',
    '## Risks',
    riskTable(recs),
    '',
    '## Rollout',
    todo('Order of deployment, feature flags, monitoring.'),
    '',
    '## Rollback',
    [
      created.length ? `Remove files that were created: ${created.slice(0, 20).map((p) => `\`${cell(p, 80)}\``).join(', ')}.` : 'No files were created.',
      deleted.length ? `Restore files that were deleted: ${deleted.slice(0, 20).map((p) => `\`${cell(p, 80)}\``).join(', ')} (from version control or backup).` : 'No files were deleted.',
      gitRuns.length ? `Git operations in this session: ${gitRuns.slice(0, 8).map((r) => `\`${cell(r.op!.code, 80)}\``).join(', ')}.` : '',
    ].filter(Boolean).join('\n\n'),
    '',
    '## Open questions',
    todo('List unresolved questions for reviewers.'),
    '',
  ].join('\n');
}

/** Render a session as a draft SRE-style document in Markdown. Pure: same input, same output. */
export function buildReport(input: ReportInput): string {
  const recs = records(input.items);
  switch (input.kind) {
    case 'pir':
      return pir(input, recs);
    case 'rca':
      return rca(input, recs);
    case 'changelog':
      return changelog(input, recs);
    case 'rfc':
      return rfc(input, recs);
  }
}
